import 'dart:developer';

import 'package:mivo/core/model/ai_questions.dart';
import 'package:mivo/core/model/custom_link.dart';
import 'package:mivo/core/model/personal_info.dart';
import 'package:mivo/core/model/setting_model.dart';
import 'package:mivo/feature/supabase_data/s_config.dart';

import 'package:supabase_flutter/supabase_flutter.dart';

class SupabaseDatabase {
  SupabaseDatabase._();
  static final SupabaseDatabase instance = SupabaseDatabase._();
  static final supabase = Supabase.instance.client;
  final database = Supabase.instance.client.from(
    SupabaseConfig.tablePersonalInfo,
  );
  Future<MyInfoModel?> getMyInfo() async {
    final response = await supabase
        .from(SupabaseConfig.tablePersonalInfo)
        .select();
    log(name: 'personal_info_response', response.toString());
    return MyInfoModel.fromJson(response[0]);
  }

  Future<SettingModel?> getSettings() async {
    final response = await supabase.from(SupabaseConfig.tableSetting).select();
    log(name: 'setting_response', response.toString());
    return SettingModel.fromJson(response[0]);
  }

  // ---------------------- Personal links (?c=code) ----------------------

  /// Website: who this link was made for, or null for a bad/inactive code.
  /// Also records the open (at most once per [visitorId] per day).
  Future<LinkGreeting?> openCustomLink(
    String code, {
    String? lang,
    String? visitorId,
  }) async {
    final rows = await supabase.rpc(
      SupabaseConfig.rpcOpenCustomLink,
      params: {'p_code': code, 'p_lang': lang, 'p_visitor': visitorId},
    );
    if (rows is! List || rows.isEmpty) return null;
    final row = Map<String, dynamic>.from(rows.first as Map);
    final description = (row['description'] as String?)?.trim();
    return LinkGreeting(
      name: row['name'] as String,
      description: (description == null || description.isEmpty)
          ? null
          : description,
    );
  }

  /// Admin (mobile): all personal links, newest first.
  Future<List<CustomLink>> getCustomLinks() async {
    final response = await supabase
        .from(SupabaseConfig.tableCustomLinks)
        .select()
        .order('created_at', ascending: false);
    return response.map<CustomLink>(CustomLink.fromJson).toList();
  }

  /// Admin (mobile): creates a link; the code is generated by the database.
  /// Throws [PostgrestException] with code 23505 if the name already exists.
  Future<CustomLink> createCustomLink({
    required String name,
    String? description,
  }) async {
    final desc = description?.trim();
    final row = await supabase
        .from(SupabaseConfig.tableCustomLinks)
        .insert({
          'name': name.trim(),
          'description': (desc == null || desc.isEmpty) ? null : desc,
        })
        .select()
        .single();
    return CustomLink.fromJson(row);
  }

  /// Starter questions shown as chips before the visitor asks anything.
  /// [lang] is 'en' or 'ar'. Managed from the `suggested_questions` table.
  Future<List<String>> getSuggestedQuestions(String lang) async {
    final response = await supabase
        .from(SupabaseConfig.tableSuggestedQuestions)
        .select('question')
        .eq('lang', lang)
        .eq('is_active', true)
        .order('sort_order', ascending: true);

    return response
        .map<String>((e) => (e['question'] ?? '').toString().trim())
        .where((q) => q.isNotEmpty)
        .toList();
  }

  Future<List<QuestionModel>> getQuestions() async {
    final response = await supabase
        .from(SupabaseConfig.tableQuestions)
        .select()
        .order('created_at', ascending: false);

    return response
        .map<QuestionModel>((e) => QuestionModel.fromJson(e))
        .toList();
  }
}
